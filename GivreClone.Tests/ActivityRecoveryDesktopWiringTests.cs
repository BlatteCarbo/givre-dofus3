extern alias F06App;

using System;
using System.IO;
using System.Reflection;
using Xunit;
using ViewModel = F06App::GivreClone.App.ViewModels.BotsViewModel;

namespace GivreClone.Tests;

public sealed class ActivityRecoveryDesktopWiringTests
{
    private static string Root => MappingScan.WalkUp(directory =>
        File.Exists(Path.Combine(directory.FullName, "GivreClone.App", "Views", "BotsView.axaml")))?.FullName
        ?? throw new InvalidOperationException("Desktop view source unavailable");

    [Fact]
    public void Real_desktop_viewmodel_exposes_inspection_and_observable_quarantine()
    {
        Assert.NotNull(typeof(ViewModel).GetProperty("ActivityRecoveryStatusText",
            BindingFlags.Instance | BindingFlags.Public));
        Assert.NotNull(typeof(ViewModel).GetProperty("ActivityRecoveryStatusVisible",
            BindingFlags.Instance | BindingFlags.Public));
        // Generated by the actual application's [RelayCommand] source generator.
        Assert.NotNull(typeof(ViewModel).GetProperty("InspectActivityRecoveryCommand",
            BindingFlags.Instance | BindingFlags.Public));
        string view = File.ReadAllText(Path.Combine(Root, "GivreClone.App", "Views", "BotsView.axaml"));
        Assert.Contains("{Binding InspectActivityRecoveryCommand}", view);
        Assert.Contains("{Binding ActivityRecoveryStatusText}", view);
        Assert.Contains("{Binding ActivityRecoveryStatusVisible}", view);
    }

    [Fact]
    public void Desktop_status_comes_from_selected_host_and_durable_read_not_fake_ack()
    {
        string vm = File.ReadAllText(Path.Combine(Root, "GivreClone.App", "ViewModels",
            "BotsViewModel.ActivityRecovery.cs"));
        Assert.Contains("_luaHosts.TryGetValue(bot.Pid, out var host)", vm);
        Assert.Contains("host.ActivityRecoveryStatus", vm);
        // The V10 UI takes the host on the UI thread, then performs durable
        // disk inspection asynchronously with profile/selection revocation.
        Assert.Contains("GivreLuaHost host = GetOrCreateHost(bot.Pid);", vm);
        // V18's actual host method also calls the V17 causal projection and
        // performs durable reconciliation. Neither result is ACK or send.
        Assert.Contains("host.RefreshActivityRecoveryTransitionsV18Status()", vm);
        Assert.Contains("causal = host.ActivityRecoveryCausalNextStepStatus;", vm);
        Assert.Contains("reconciliation = host.ActivityRecoveryReconciliationStatus;", vm);
        Assert.Contains("await Task.Run(", vm);
        Assert.Contains("durable = transitions.DurableStatus;", vm);
        Assert.Contains("_activityRecoveryInspectedTransitionsV18 = transitions;", vm);
        Assert.Contains("_activityRecoveryInspectedReconciliation = reconciliation;", vm);
        Assert.Contains("_activityRecoveryInspectedNextV17 = causal;", vm);
        Assert.Contains("Interlocked.Read(ref _mapAttackSelectionGeneration) != selection", vm);
        Assert.Contains("character != Stores.Launch.CharacterId((uint)bot.Pid)", vm);
        Assert.Contains("ActivityRecoveryReconciliationDecision.PendingQuarantine", vm);
        Assert.Contains("Preuve non attribuable ; quarantaine maintenue.", vm);
        Assert.Contains("Aucun reçu serveur individuel ni reprise automatique.", vm);
        Assert.Contains("Aucun second envoi", vm);
        Assert.DoesNotContain("ConfirmCorrelatedAck(", vm);
        Assert.DoesNotContain("SendCast(", vm);
        Assert.DoesNotContain("SendHarvest(", vm);
    }
}
